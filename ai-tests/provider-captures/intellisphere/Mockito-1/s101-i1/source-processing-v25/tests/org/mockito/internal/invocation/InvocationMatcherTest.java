    @Test
    public void testHasSimilarMethod_OverloadedButSameArgs_ShouldReturnFalse() throws Exception {
        Object mockObj = new Object();
        // Two different methods with same name but different parameter types
        Method method1 = String.class.getMethod("indexOf", String.class);
        Method method2 = String.class.getMethod("indexOf", int.class);
        Invocation inv = mock(Invocation.class);
        when(inv.getMethod()).thenReturn(method1);
        when(inv.getMock()).thenReturn(mockObj);

        Invocation candidate = mock(Invocation.class);
        when(candidate.getMethod()).thenReturn(method2);
        when(candidate.getMock()).thenReturn(mockObj);
        when(candidate.isVerified()).thenReturn(false);
        // arguments that will match (even though method signatures differ)
        // The argument matching uses the matchers built from inv's arguments,
        // which we need to set to match candidate's arguments.
        when(inv.getArguments()).thenReturn(new Object[]{new Integer(5)});
        when(candidate.getArguments()).thenReturn(new Object[]{new Integer(5)});

        InvocationMatcher matcher = new InvocationMatcher(inv);
        assertFalse(matcher.hasSimilarMethod(candidate));
    }

