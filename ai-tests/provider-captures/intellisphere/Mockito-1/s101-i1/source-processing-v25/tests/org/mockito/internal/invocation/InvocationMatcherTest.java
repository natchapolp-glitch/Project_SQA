    @Test
    public void testIsVarargMatcher_DirectVarargMatcher_ReturnsTrue() throws Exception {
        InvocationMatcher matcher = new InvocationMatcher(mock(Invocation.class));
        // private method isVarargMatcher
        java.lang.reflect.Method method = InvocationMatcher.class.getDeclaredMethod("isVarargMatcher", Matcher.class);
        method.setAccessible(true);

        // Create a matcher that implements VarargMatcher
        Matcher varargMatcher = mock(Matcher.class, withSettings().extraInterfaces(VarargMatcher.class));

        Boolean result = (Boolean) method.invoke(matcher, varargMatcher);
        assertTrue(result);
    }

