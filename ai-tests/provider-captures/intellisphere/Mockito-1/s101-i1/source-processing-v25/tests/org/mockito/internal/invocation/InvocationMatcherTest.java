    @Test
    public void testConstructorWithEmptyMatchersList_ShouldConvertArgumentsToMatchers() {
        Invocation invocation = mock(Invocation.class);
        when(invocation.getArguments()).thenReturn(new Object[]{"arg1", "arg2"});

        InvocationMatcher matcher = new InvocationMatcher(invocation, Collections.<Matcher>emptyList());
        List<Matcher> matchers = matcher.getMatchers();
        assertNotNull(matchers);
        assertFalse("matchers should not be empty for non-empty arguments", matchers.isEmpty());
        // verify that the matchers are the ones generated by ArgumentsProcessor,
        // which are typically Equals matchers. At minimum they are not null.
        for (Matcher m : matchers) {
            assertNotNull(m);
        }
    }

    @Test
    public void testConstructorWithNonEmptyMatchersList_ShouldUseGivenMatchers() {
        Invocation inv = mock(Invocation.class);
        Matcher matcher1 = mock(Matcher.class);
        Matcher matcher2 = mock(Matcher.class);
        List<Matcher> inputMatchers = Arrays.asList(matcher1, matcher2);

        InvocationMatcher matcher = new InvocationMatcher(inv, inputMatchers);
        List<Matcher> result = matcher.getMatchers();
        assertSame("should use the provided list", inputMatchers, result);
        assertSame(matcher1, result.get(0));
        assertSame(matcher2, result.get(1));
    }

