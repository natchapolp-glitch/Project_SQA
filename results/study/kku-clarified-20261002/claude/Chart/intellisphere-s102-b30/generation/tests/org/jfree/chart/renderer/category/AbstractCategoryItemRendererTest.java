    /**
     * Test getItemLabelGenerator() prioritizes series generator over base.
     */
    public void testGetItemLabelGeneratorResolution() {
        CategoryItemLabelGenerator baseGen = new CategoryItemLabelGenerator() {
            public String generateLabel(CategoryDataset dataset, int row, int column) {
                return "Base";
            }
        };
        CategoryItemLabelGenerator seriesGen = new CategoryItemLabelGenerator() {
            public String generateLabel(CategoryDataset dataset, int row, int column) {
                return "Series";
            }
        };
        
        renderer.setBaseItemLabelGenerator(baseGen);
        renderer.setSeriesItemLabelGenerator(0, seriesGen);
        
        // Row 0 with series generator: should return series generator
        assertSame("Should return series generator for row 0", seriesGen,
                renderer.getItemLabelGenerator(0, 0, false));
        
        // Row 1 without series generator: should return base generator
        assertSame("Should return base generator for row 1", baseGen,
                renderer.getItemLabelGenerator(1, 0, false));
        
        // No base generator set: should return null
        renderer.setBaseItemLabelGenerator(null);
        assertNull("Should return null when no series or base generator", 
                renderer.getItemLabelGenerator(1, 0, false));
    }

